export type EntityEntry = { word: string; categoryId: string };

/**
 * Builds a flat pool of {word, categoryId} pairs across the given categories.
 * Keeping the word paired with the category it came from is important: the
 * secret word and the category shown as the imposter's hint must always be
 * picked together, otherwise (with more than one category selected) they can
 * end up mismatched — e.g. the word "Pizza" paired with the "Animals" hint.
 */
export function getEntityPool(categoryIds: string[]): EntityEntry[] {
  const pool: EntityEntry[] = [];
  categoryIds.forEach((id) => {
    (entities[id] ?? []).forEach((word) => pool.push({ word, categoryId: id }));
  });
  return pool;
}
